"""Does splitting a daily return into its night and day halves predict anything?

PRE-REGISTRATION (written before the first run; see
`docs/experiment_day_night_2026-10-25.md` for the recorded result)
---------------------------------------------------------------------
A daily bar decomposes into two disjoint returns that are *not* the same
economic object:

    night_t   = ln(open_t / close_{t-1})      # markets closed, no trading
    day_t     = ln(close_t / open_t)          # the session itself
    close_t   = night_t + day_t               # what close-to-close measures

`state/registry/failed_hypotheses.json` records seven dormant hypotheses,
and every one of them is built on close-to-close returns
(`voltarget_tsmom`, `reversal_short_horizon`, `vix_term_structure`,
`seasonality_turn_of_month`, `lowvol_regime_trend`,
`cross_asset_leadlag`). The decomposition has never been tested here, so
this is a distinct question rather than a re-run of a failed one -- the
distinction the research brief insists on.

**Four sub-hypotheses, declared as one family.** They share a data source,
a mechanism family and a test procedure, so they are corrected together
and never reported as four independent discoveries:

    NIGHT_DAY     night_t   -> day_t          (same bar; see "tradeability")
    DAY_NIGHT     day_t     -> night_{t+1}
    DAY_DAY       day_t     -> day_{t+1}
    CLOSE_CLOSE   close_t   -> close_{t+1}    (control: the failed baseline)

**Tradeability.** NIGHT_DAY is the only one whose signal is available
before its target begins: the overnight return is known at the opening
auction, and the target runs from that open to the close. The other three
are also implementable, one bar later. A rule whose signal were only known
at the close of the bar it predicts would be untradeable, and none is.

**Primary statistic.** The out-of-sample mean of `sign(predictor) *
target`, which is the log return of a parameter-free long/short timing
rule. Parameter-free on purpose: a fitted coefficient would need its own
multiple-testing account, and the sign rule cannot be tuned.

**Null model.** Not "zero". An equity index drifts up, so a rule that
happens to be long more often than short earns a positive mean with no
timing ability at all. The null is therefore generated by *circular block
shifts* of the predictor against the targets: that destroys the alignment
under test while preserving each series' own distribution and serial
dependence, including the drift. The p-value is the share of shifted
statistics at least as large as the observed one. Reported alongside:
the always-long benchmark and NO_TRADE (identically zero).

**Economic endpoint.** The statistic is in log-return units of the
*underlying* per round trip, and the rule trades every bar. So its value
is directly the largest round-trip cost the edge could bear. For a turbo
of leverage L the underlying edge must exceed `spread_turbo / L`, so the
break-even is reported in underlying terms and left to be compared against
a measured spread rather than a guessed one.

**Falsification.** The family fails if no sub-hypothesis survives
Benjamini-Hochberg at alpha=0.10 across all (sub-hypothesis, underlying)
cells, or if the surviving cells' break-even cost is below a plausible
round-trip cost. A positive screen here is an `ALPHA_CANDIDATE` and
nothing more: it is measured on DEVELOPMENT data, which
`research/partitions.py` defines as never being evidence.

WHAT THIS MODULE IS NOT
-----------------------
It is not P06 (Gao, Han, Li and Zhou 2018, *Market Intraday Momentum*,
JFE). That paper's claim is that the **first half-hour** return predicts
the **last half-hour** return on SPY. A daily bar contains neither. Tested
2026-10-25: 30-minute history reaches 60 days and hourly reaches 730, so
P06 is `AWAIT_DATA` on the measured ground that the data does not exist at
the needed depth, not because it was judged uninteresting.

This module is read-only. It promotes nothing, changes no weight, gate or
threshold, and is allowed to answer that the sample is too small.
"""

from __future__ import annotations

import math
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum

import numpy as np
import numpy.typing as npt

from turboedge.backtest.purged_cv import PurgedWalkForwardSplit
from turboedge.storage.schemas import UnderlyingBar

#: Minimum out-of-sample observations before a cell is reported at all.
#: Below this the sign rule's mean is dominated by a handful of days and a
#: p-value from it would be theatre.
MIN_OOS_OBSERVATIONS = 250


class SubHypothesis(StrEnum):
    """The declared predictor -> target pairs.

    The first four were pre-registered. The last two were added after the
    mandatory look-ahead audit (see :func:`shares_a_price`) failed the
    first four's most promising cell, and they exist to answer the question
    that failure raises: does anything survive when the signal and the
    target have no price in common? They are added to the family rather
    than replacing it, so the multiple-testing denominator only grows.
    """

    NIGHT_DAY = "NIGHT_DAY"
    DAY_NIGHT = "DAY_NIGHT"
    DAY_DAY = "DAY_DAY"
    CLOSE_CLOSE = "CLOSE_CLOSE"
    NIGHT_NEXT_DAY = "NIGHT_NEXT_DAY"
    NIGHT_NEXT_CLOSE = "NIGHT_NEXT_CLOSE"


def shares_a_price(sub: SubHypothesis) -> bool:
    """Whether this pair's predictor and target are built from one price.

    THE AUDIT THAT OVERTURNED THIS EXPERIMENT'S FIRST RESULT.

    ``night_t = ln(O_t / C_{t-1})`` and ``day_t = ln(C_t / O_t)`` both
    contain ``O_t``, with opposite signs. Two consequences, and they pull
    in opposite directions, which is why the check has to be structural
    rather than a judgement about which one dominates:

    * Independent measurement error in ``O_t`` enters night as ``+e`` and
      day as ``-e``, so it anti-correlates them and biases a
      ``sign(night) * day`` rule *down*.
    * A **stale** open -- one computed before every constituent has
      actually traded, so it is pulled toward ``C_{t-1}`` -- leaves part of
      the true overnight gap inside ``day_t`` as well as inside
      ``night_t``, with the *same* sign. That inflates the rule without
      any predictability existing.

    Measured on real history (2026-10-25): ``corr(night, day)`` is +0.2640
    on the Euro Stoxx 50 and +0.0277 on the DAX. A quarter-correlation
    between an overnight gap and the session that follows it is not a
    market fact, it is the second mechanism. Removing the shared price
    shrank the rule's mean by a factor of 25 on SX5E and 5 on the DAX.

    There is also a plain implementability objection that applies whatever
    the data quality: the signal is only complete once ``O_t`` is known,
    and the target starts at ``O_t``. No one can both read the opening
    price and transact at it.

    A cell that shares a price can therefore never be reported as a
    candidate -- only as ``LOOKAHEAD_SUSPECT``.
    """
    return sub is SubHypothesis.NIGHT_DAY


@dataclass(frozen=True, slots=True)
class ReturnParts:
    """Night, day and close-to-close log returns, aligned and gap-free.

    All three arrays are indexed by bar and start at the second usable bar,
    since every component needs a previous close.
    """

    night: npt.NDArray[np.float64]
    day: npt.NDArray[np.float64]
    close_to_close: npt.NDArray[np.float64]

    def __post_init__(self) -> None:
        if not (self.night.shape == self.day.shape == self.close_to_close.shape):
            raise ValueError("night, day and close_to_close must have the same shape")


def decompose(bars: Sequence[UnderlyingBar]) -> ReturnParts:
    """Split daily bars into their overnight and intraday halves.

    Bars are sorted by ``ts`` and de-duplicated on it, keeping the last
    occurrence, because a re-fetched day legitimately appears twice in the
    archive and a duplicate would fabricate a zero-return night.

    A bar whose open, high, low or close is not positive is dropped rather
    than repaired, and dropping it also drops the night that would have
    been measured across the hole: ``ln(open_t / close_{t-1})`` across a
    gap in the series is not an overnight return, it is a multi-day one.
    That is what makes this function refuse to silently stitch.

    Raises:
        ValueError: if fewer than two usable bars remain.
    """
    by_ts: dict[object, UnderlyingBar] = {}
    for bar in sorted(bars, key=lambda b: b.ts):
        by_ts[bar.ts] = bar
    ordered = list(by_ts.values())

    nights: list[float] = []
    days: list[float] = []
    previous: UnderlyingBar | None = None
    for bar in ordered:
        usable = bar.open > 0 and bar.high > 0 and bar.low > 0 and bar.close > 0
        if not usable:
            # Drop the bar *and* break the chain: the next night would
            # otherwise span the hole.
            previous = None
            continue
        if previous is not None:
            nights.append(math.log(bar.open / previous.close))
            days.append(math.log(bar.close / bar.open))
        previous = bar

    if len(nights) < 2:
        raise ValueError(f"need at least 2 usable consecutive bars, got {len(nights)}")
    night = np.asarray(nights, dtype=np.float64)
    day = np.asarray(days, dtype=np.float64)
    return ReturnParts(night=night, day=day, close_to_close=night + day)


def _pair(
    parts: ReturnParts, sub: SubHypothesis
) -> tuple[npt.NDArray[np.float64], npt.NDArray[np.float64]]:
    """The (predictor, target) arrays for one sub-hypothesis.

    NIGHT_DAY aligns within the bar; the other three shift the target
    forward by one bar, which is what makes their signal known before the
    target starts.
    """
    if sub is SubHypothesis.NIGHT_DAY:
        return parts.night, parts.day
    if sub is SubHypothesis.DAY_NIGHT:
        return parts.day[:-1], parts.night[1:]
    if sub is SubHypothesis.DAY_DAY:
        return parts.day[:-1], parts.day[1:]
    if sub is SubHypothesis.NIGHT_NEXT_DAY:
        return parts.night[:-1], parts.day[1:]
    if sub is SubHypothesis.NIGHT_NEXT_CLOSE:
        return parts.night[:-1], parts.close_to_close[1:]
    return parts.close_to_close[:-1], parts.close_to_close[1:]


def _circular_shift_null(
    predictor: npt.NDArray[np.float64],
    target: npt.NDArray[np.float64],
    *,
    draws: int,
    min_shift: int,
    rng: np.random.Generator,
) -> npt.NDArray[np.float64]:
    """Null distribution of the rule's mean under broken alignment.

    Rolling the predictor rather than shuffling it keeps its own serial
    dependence and the target's drift intact, so the only thing destroyed
    is the correspondence between them -- which is the hypothesis. A
    shuffle would also destroy the autocorrelation and make the null too
    narrow.

    ``min_shift`` keeps the roll away from near-identity alignments, which
    would otherwise be counted as null samples that still contain most of
    the effect.
    """
    n = predictor.size
    stats = np.empty(draws, dtype=np.float64)
    usable = max(1, n - 2 * min_shift)
    offsets = rng.integers(min_shift, min_shift + usable, size=draws)
    for i, offset in enumerate(offsets):
        rolled = np.roll(predictor, int(offset))
        stats[i] = float(np.mean(np.sign(rolled) * target))
    return stats


@dataclass(frozen=True, slots=True)
class CellResult:
    """One (underlying, sub-hypothesis) measurement, out of sample."""

    underlying_id: str
    sub_hypothesis: SubHypothesis
    n_oos: int
    rule_mean: float
    always_long_mean: float
    directional_accuracy: float
    p_value: float
    ci_low: float
    ci_high: float
    folds: int
    night_day_correlation: float = float("nan")

    @property
    def shares_a_price_with_target(self) -> bool:
        return shares_a_price(self.sub_hypothesis)

    @property
    def break_even_round_trip_cost(self) -> float:
        """Largest round-trip cost, in underlying log return, the edge bears.

        The rule trades every bar, so the per-trade budget *is* the mean.
        Negative means there is nothing to spend.
        """
        return self.rule_mean

    @property
    def sufficient(self) -> bool:
        return self.n_oos >= MIN_OOS_OBSERVATIONS


def evaluate_cell(
    bars: Sequence[UnderlyingBar],
    *,
    underlying_id: str,
    sub_hypothesis: SubHypothesis,
    min_train: int = 500,
    step: int = 250,
    embargo: int = 1,
    null_draws: int = 2000,
    seed: int = 20261025,
) -> CellResult:
    """Walk-forward evaluate one sub-hypothesis on one underlying.

    The sign rule has nothing to fit, so the walk-forward is not protecting
    a parameter estimate -- it is enforcing that every reported observation
    comes from a block the procedure had not seen when the family was
    declared, and that the fold structure is fixed rather than chosen after
    the fact. ``horizon=1`` with ``embargo=1``: these targets are
    single-bar and non-overlapping, so the effective sample equals the
    nominal one, which is the rare case where no uniqueness correction is
    needed.

    Raises:
        ValueError: if the bars cannot be decomposed, or ``null_draws`` is
            below 100 -- a p-value from fewer draws has a resolution
            coarser than the thresholds it would be compared against.
    """
    if null_draws < 100:
        raise ValueError(f"null_draws must be >= 100, got {null_draws!r}")
    parts = decompose(bars)
    # Recorded on every cell, not just the shared-price one: it is the
    # diagnostic that identifies a stale open, and it is a property of the
    # underlying's data rather than of the pair under test.
    night_day_corr = (
        float(np.corrcoef(parts.night, parts.day)[0, 1]) if parts.night.size > 2 else float("nan")
    )
    predictor, target = _pair(parts, sub_hypothesis)
    n = predictor.size
    if n == 0:
        raise ValueError("no aligned observations")

    axis = np.arange(n, dtype=np.int64)
    splitter = PurgedWalkForwardSplit(horizon=1, embargo=embargo, min_train=min_train, step=step)
    oos_pred: list[float] = []
    oos_targ: list[float] = []
    folds = 0
    for _train_idx, test_idx in splitter.split(axis, axis + 1):
        if test_idx.size == 0:
            continue
        folds += 1
        oos_pred.extend(predictor[test_idx].tolist())
        oos_targ.extend(target[test_idx].tolist())

    if not oos_pred:
        return CellResult(
            underlying_id=underlying_id,
            sub_hypothesis=sub_hypothesis,
            n_oos=0,
            rule_mean=float("nan"),
            always_long_mean=float("nan"),
            directional_accuracy=float("nan"),
            p_value=float("nan"),
            ci_low=float("nan"),
            ci_high=float("nan"),
            folds=0,
            night_day_correlation=night_day_corr,
        )

    p_arr = np.asarray(oos_pred, dtype=np.float64)
    t_arr = np.asarray(oos_targ, dtype=np.float64)
    realised = np.sign(p_arr) * t_arr
    rule_mean = float(np.mean(realised))

    rng = np.random.default_rng(seed)
    null_stats = _circular_shift_null(
        p_arr, t_arr, draws=null_draws, min_shift=max(5, p_arr.size // 50), rng=rng
    )
    # One-sided: the hypothesis is that the rule earns *more* than chance.
    # The +1 is the standard finite-sample correction, so a p-value can
    # never be reported as exactly zero from a finite number of draws.
    p_value = float((np.sum(null_stats >= rule_mean) + 1) / (null_stats.size + 1))

    # Interval for the rule's own mean, by bootstrap over observations.
    # Single-bar targets do not overlap, so an ordinary bootstrap is the
    # right one here and a block bootstrap would only lose precision.
    boot = rng.choice(realised, size=(2000, realised.size), replace=True).mean(axis=1)
    return CellResult(
        underlying_id=underlying_id,
        sub_hypothesis=sub_hypothesis,
        n_oos=int(realised.size),
        rule_mean=rule_mean,
        always_long_mean=float(np.mean(t_arr)),
        directional_accuracy=float(np.mean(np.sign(p_arr) == np.sign(t_arr))),
        p_value=p_value,
        ci_low=float(np.quantile(boot, 0.025)),
        ci_high=float(np.quantile(boot, 0.975)),
        folds=folds,
        night_day_correlation=night_day_corr,
    )


def benjamini_hochberg(p_values: Sequence[float], *, alpha: float = 0.10) -> list[bool]:
    """Which cells survive BH at ``alpha``, treating all of them as one family.

    The brief's rule, and the repository's (GOVERNANCE.md §11.2): related
    sub-hypotheses of one research family are not independent discoveries.
    ``nan`` p-values never survive.

    Raises:
        ValueError: if ``alpha`` is outside ``(0, 1)``.
    """
    if not 0.0 < alpha < 1.0:
        raise ValueError(f"alpha must be in (0, 1), got {alpha!r}")
    arr = np.asarray(p_values, dtype=np.float64)
    m = arr.size
    if m == 0:
        return []
    finite = np.isfinite(arr)
    order = np.argsort(np.where(finite, arr, np.inf), kind="stable")
    survive = np.zeros(m, dtype=bool)
    threshold_rank = 0
    for rank, idx in enumerate(order, start=1):
        if not finite[idx]:
            break
        if arr[idx] <= alpha * rank / m:
            threshold_rank = rank
    for rank, idx in enumerate(order, start=1):
        if rank <= threshold_rank:
            survive[idx] = True
    return survive.tolist()


@dataclass(frozen=True, slots=True)
class FamilyResult:
    """The whole family, with its multiple-testing verdict."""

    cells: tuple[CellResult, ...]
    survives: tuple[bool, ...]
    alpha: float

    @property
    def verdict(self) -> str:
        """`evaluate_excursion`'s vocabulary, so the loop reads one language.

        CANDIDATE only when a cell survives correction *and* its interval
        excludes zero. A surviving p-value whose interval straddles zero is
        a direction without a magnitude, and sizing it would be guessing.
        """
        if not self.cells:
            return "INSUFFICIENT_SAMPLE"
        if not any(c.sufficient for c in self.cells):
            return "INSUFFICIENT_SAMPLE"
        passing = [
            c
            for c, s in zip(self.cells, self.survives, strict=True)
            if s and c.sufficient and c.ci_low > 0.0
        ]
        clean = [c for c in passing if not c.shares_a_price_with_target]
        if clean:
            return "CANDIDATE"
        if passing:
            # Something survived correction, but only through a cell whose
            # signal and target share a price. That is the look-ahead
            # audit failing, and the brief is explicit: a positive strategy
            # that fails it is discarded, not reported as a candidate.
            return "LOOKAHEAD_SUSPECT"
        if any(s for s in self.survives):
            return "IMPROVEMENT_NOT_SIGNIFICANT"
        return "NO_IMPROVEMENT"

    @property
    def best_break_even_cost(self) -> float:
        """Largest round-trip cost budget among surviving cells, else nan."""
        budgets = [
            c.break_even_round_trip_cost
            for c, s in zip(self.cells, self.survives, strict=True)
            if s and c.sufficient and not c.shares_a_price_with_target
        ]
        return max(budgets) if budgets else float("nan")


def evaluate_family(
    bars_by_underlying: Mapping[str, Sequence[UnderlyingBar]],
    *,
    alpha: float = 0.10,
    min_train: int = 500,
    step: int = 250,
    null_draws: int = 2000,
    seed: int = 20261025,
) -> FamilyResult:
    """Run all four sub-hypotheses on every underlying and correct together.

    Underlyings are iterated in sorted order so the family's p-value vector
    -- and therefore the BH ranking -- does not depend on dict insertion
    order.
    """
    cells: list[CellResult] = []
    for underlying_id in sorted(bars_by_underlying):
        bars = bars_by_underlying[underlying_id]
        for sub in SubHypothesis:
            try:
                cells.append(
                    evaluate_cell(
                        bars,
                        underlying_id=underlying_id,
                        sub_hypothesis=sub,
                        min_train=min_train,
                        step=step,
                        null_draws=null_draws,
                        seed=seed,
                    )
                )
            except ValueError:
                # An underlying with too little usable history contributes
                # nothing rather than aborting the family.
                continue
    survives = benjamini_hochberg([c.p_value for c in cells], alpha=alpha)
    return FamilyResult(cells=tuple(cells), survives=tuple(survives), alpha=alpha)


